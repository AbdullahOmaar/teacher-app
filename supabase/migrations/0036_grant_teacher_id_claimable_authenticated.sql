-- (SEC-L10؛ الدفعة المولّدة #11؛ 3A-377 — تصحيح بعد 0035)
--
-- ما حدث: 0034/0035 سحبتا EXECUTE من PUBLIC ثم من anon/authenticated
-- لإغلاق أوراكل تعداد المستخدمين — فأغلقتا الأوراكل فعلًا (anon الآن
-- 401)، لكن اختبارات التفويض تراجعت 37/37 ← 33/37: الإدراج الذاتي
-- وإدراج السنتر بلا id فشلا. السبب: تعبير WITH CHECK في سياسة RLS
-- يُقيَّم بصلاحيات المستدعي، فاستدعاء الدالة من السياسة يتطلب أن
-- يملك المستدعي EXECUTE عليها — والسحب من authenticated كسر السياسة.
-- (هذا هو نمط Supabase القياسي نفسه: دالة payment_proof_upload_allowed
-- ممنوحة صراحةً لـ anon/authenticated في 0005 لنفس السبب.)
--
-- الحل النهائي: المنح الأدنى العامل — authenticated فقط:
-- - anon: بلا EXECUTE (الأوراكل العام مغلق: 401) — ولا يحتاجه أصلًا،
--   فإدراج مجهول مرفوض سلفًا بـ owner_user_id = auth.uid().
-- - authenticated: يملك EXECUTE (السياسة تعمل: ذاتي 201 + سنتر 201).
-- - الأوراكل المتبقي لمستخدم مصادق (true/false لوجود UUID يعرفه
-- سلفًا): خطر منخفض موثق ومقبول — UUIDs غير قابلة للتخمين، ولا
-- يسرّب سوى الوجود، ومعرّفات المدرسين تُشارَك بالتصميم في دعوات
-- الفريق. لا طريقة لإغلاقه كليًا بلا إعادة تصميم (trigger بدل السياسة)
-- وهي خارج نطاق هذه الدفعة.
-- ===========================================================================

GRANT EXECUTE ON FUNCTION public.teacher_id_claimable(uuid) TO authenticated;
