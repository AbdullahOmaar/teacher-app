// كود العرض القصير لمعرّف الحساب (ملاحظات المالك 2026-11-28 — بند ٢)
//
// المعرّف القانوني للحساب هو الـUUID الكامل (36 حرفاً) — هو اللي بيتنسخ
// بزر النسخ وبيتلصق في نموذج «إضافة بمعرّف الحساب». لكن عرضه خاماً في
// قسم «حسابي» كان سطراً طويلاً صعب القراءة والمقارنة البصرية.
//
// الاشتقاق (طبقة عرض فقط — لا تغيير في القاعدة ولا في أي قيمة محفوظة):
//   ١) نشيل كل ما ليس رقماً سداسياً عشرياً من الـUUID.
//   ٢) ناخد أول 12 رقماً، بأحرف كبيرة.
//   ٣) نعرضهم ثلاث مجموعات من 4 بشرطة: «A8CF-C920-DD1D» (14 حرفاً).
//
// الكود مشتق حتمياً من أول 48 بت من المعرّف نفسه — نفس الحساب يدي نفس
// الكود دائماً، وهو بصمة بصرية للتعرف السريع لا بديل عن المعرّف: النسخ
// واللصق والتحقق الخادمي كلها على الـUUID الكامل كما هي.
// ===========================================================================

/** كود عرض قصير منظّم من معرّف UUID — انظر الترويسة للاشتقاق الكامل */
export function shortAccountCode(id: string): string {
  const hex = id.replace(/[^0-9a-fA-F]/g, '').toUpperCase()
  if (hex.length < 12) return id
  const head = hex.slice(0, 12)
  return `${head.slice(0, 4)}-${head.slice(4, 8)}-${head.slice(8, 12)}`
}
